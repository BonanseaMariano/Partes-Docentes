package unpsjb.labprog.backend.model.enums;

/**
 * Enumeración que representa los turnos escolares disponibles. Define los
 * horarios de funcionamiento de las divisiones académicas.
 *
 * @author Mariano Bonansea
 * @version 1.0
 */
public enum Turno {
    /**
     * Turno matutino
     */
    Mañana,
    /**
     * Turno de tarde
     */
    Tarde,
    /**
     * Turno vespertino
     */
    Vespertino,
    /**
     * Turno nocturno
     */
    Noche;
}
